// usage: node capture-prompt-and-schema.mjs <stage> <npmDir>
// Captures catalog.prompt() and catalog.jsonSchema() from the published @json-render 0.22.0 packages.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { createStage } from "./lib.mjs";

const [stageDir, npmDir] = process.argv.slice(2);
const req = createRequire(path.join(npmDir, "noop.js"));
const load = (id) => import(req.resolve(id));
const { schema } = await load("@json-render/react");
const { defineCatalog } = await load("@json-render/core");
const { shadcnComponentDefinitions } = await load("@json-render/shadcn/catalog");
const { z } = await load("zod");

const stage = createStage(stageDir, ".");
const generated = "generated by catalog.prompt() / catalog.jsonSchema() of the published packages (see MANIFEST generatedWith)";
const meta = (kind) => ({ kind, upstreamPath: "(generated)", upstreamLines: generated });

const shadcn = defineCatalog(schema, { components: shadcnComponentDefinitions, actions: {} });
stage.write("prompt/shadcn-standalone.txt", shadcn.prompt(), meta("prompt"));
stage.write("prompt/shadcn-inline.txt", shadcn.prompt({ mode: "inline" }), meta("prompt"));
stage.writeJSON("schema/shadcn.strict.json", shadcn.jsonSchema({ strict: true }), meta("schema"));
stage.writeJSON("schema/shadcn.loose.json", shadcn.jsonSchema({ strict: false }), meta("schema"));

const minimalDefs = {
  Card: {
    props: z.object({ title: z.string(), subtitle: z.string().nullable() }),
    slots: ["default", "header", "footer"],
    description: "A card",
  },
  Text: {
    props: z.object({ text: z.string(), variant: z.enum(["body", "caption"]).nullable() }),
    slots: [],
    description: "Text",
  },
};
const minimal = defineCatalog(schema, { components: minimalDefs, actions: {} });
stage.write("prompt/minimal-two-components.txt", minimal.prompt(), meta("prompt"));
stage.writeJSON("schema/minimal-two-components.strict.json", minimal.jsonSchema({ strict: true }), meta("schema"));

const describe = (defs) =>
  Object.fromEntries(
    Object.entries(defs).map(([name, d]) => [
      name,
      {
        description: d.description ?? null,
        slots: d.slots ?? [],
        events: d.events ?? [],
        props: z.toJSONSchema(d.props, { unrepresentable: "any", io: "input" }),
      },
    ]),
  );
stage.writeJSON(
  "prompt/catalogs.json",
  {
    note: "Exact catalog inputs behind the prompt and schema files. props is the JSON Schema of the zod props object.",
    schema: "@json-render/react schema; actions: {}",
    catalogs: {
      "shadcn": { components: describe(shadcnComponentDefinitions) },
      "minimal-two-components": { components: describe(minimalDefs) },
    },
  },
  meta("catalog-input"),
);

// Package versions and integrity, from the npm lock written by the install.
const lock = JSON.parse(fs.readFileSync(path.join(npmDir, "node_modules/.package-lock.json"), "utf8"));
const generatedWith = {};
for (const name of ["@json-render/core", "@json-render/react", "@json-render/shadcn", "zod", "react", "react-dom", "typescript"]) {
  // Lock keys are relative to the npm working directory, so match by suffix.
  const key = Object.keys(lock.packages).find((k) => k === `node_modules/${name}` || k.endsWith(`/node_modules/${name}`));
  const e = lock.packages[key];
  generatedWith[name] = { version: e.version, integrity: e.integrity };
}
fs.writeFileSync(path.join(stageDir, ".generated-with.json"), JSON.stringify(generatedWith, null, 2));
stage.flushEntries(".entries-prompt.json");
console.log("prompt+schema: " + stage.entries.length + " files");
