#!/usr/bin/env python3
"""Render docs/parity.md from a Swift Testing xunit file and the fixture folders.

Usage: render.py <xunit-dir> <MANIFEST.json> <toolchain-line>

Standard library only; no network. The xunit file is the `*-swift-testing.xml` that
`swift test --xunit-output <path>.xml` writes next to `<path>.xml`. Swift Testing reports one
test case per test function, so a parameterised test counts once; the case counts come from the
fixture folders themselves (their `index.json` rows), as `FixtureInventoryTests` also checks.

Output goes to stdout. It is the same for the same tree and toolchain results. The only
lines that can differ between machines are the generation comment (date, toolchain), which
starts with `<!-- generated`; CI ignores it when it checks for drift.
"""
import collections
import datetime
import glob
import json
import os
import sys
import xml.etree.ElementTree as ET

xunit_dir, manifest_path, toolchain = sys.argv[1], sys.argv[2], sys.argv[3]
fixtures = os.path.dirname(os.path.dirname(os.path.abspath(manifest_path)))  # Tests/ParityFixtures

manifest = json.load(open(manifest_path, encoding="utf-8"))
upstream = manifest["upstream"]

# Results per suite (class) from the xunit file.
results = collections.defaultdict(lambda: {"passed": 0, "failed": 0, "skipped": 0})
files = sorted(glob.glob(os.path.join(xunit_dir, "*swift-testing*.xml")))
if not files:
    sys.exit("no *-swift-testing.xml file in " + xunit_dir)
for path in files:
    for case in ET.parse(path).getroot().iter("testcase"):
        suite = case.get("classname", "").split(".")[-1]
        if case.find("failure") is not None or case.find("error") is not None:
            results[suite]["failed"] += 1
        elif case.find("skipped") is not None:
            results[suite]["skipped"] += 1
        else:
            results[suite]["passed"] += 1


def count_rows(relative):
    """Case count of a fixture folder: the rows of its index.json, else its files."""
    folder = os.path.join(fixtures, relative)
    index = os.path.join(folder, "index.json")
    if os.path.exists(index):
        rows = json.load(open(index, encoding="utf-8"))
        if isinstance(rows, dict):
            rows = rows.get("fixtures", rows)
        return len(rows)
    return len([f for f in os.listdir(folder) if not f.startswith(".") and f != "index.json"])


def sources(folder):
    """The upstream files that a manifest folder was made from."""
    found = set()
    generated = False
    for row in manifest["files"]:
        if row["path"].startswith(folder + "/"):
            origin = row.get("upstreamPath", "")
            if origin == "(generated)":
                generated = True
            elif origin and origin != "(case list)":
                found.add(origin)
    if generated:
        return "generated by the published 0.22.0 packages"
    return "<br>".join("`" + s + "`" for s in sorted(found)) or "transcribed cases"


# (folder, Swift suites that read it). A folder is "pass" when every listed suite ran and
# nothing failed. The mapping is the one place to edit when a suite is renamed.
UPSTREAM = [
    ("state", ["PathOpsParityTests"]),
    ("expressions", ["ExpressionParityTests", "DirectiveTests", "ComputedTests"]),
    ("visibility", ["VisibilityParityTests", "VisibilityDecodeTests"]),
    ("actions", ["ActionParityTests"]),
    ("validation", ["ValidationParityTests", "BuiltInValidationTests", "FormValidatorTests"]),
    ("validator", ["SpecValidatorParityTests"]),
    ("specs", ["FixtureInventoryTests"]),
    ("prompt", ["PromptParityTests"]),
    ("schema", ["JSONSchemaParityTests"]),
    ("streams", ["StreamParityTests"]),
]
OWN = [
    ("streams", "Our own stream transcripts (out of order, root last, malformed line, fragments)", ["StreamParityTests"]),
    ("charts", "Chart specs for the mark charts", ["ChartFixtureTests"]),
    ("charts/composite", "Chart specs for the composite charts", ["CompositeFixtureTests"]),
    ("compose", "Recorded Decisions API answers for the composer", ["ComposeFixtureInventoryTests", "BatchedCompositionParityTests"]),
]


def verdict(suites):
    missing = [s for s in suites if s not in results]
    failed = sum(results[s]["failed"] for s in suites if s in results)
    tests = sum(sum(results[s].values()) for s in suites if s in results)
    skipped = sum(results[s]["skipped"] for s in suites if s in results)
    if missing:
        return tests, "NOT RUN: " + ", ".join(missing)
    if failed:
        return tests, "FAIL (%d)" % failed
    return tests, "pass" + (" (%d skipped)" % skipped if skipped else "")


out = []
w = out.append
w("# Parity report")
w("")
w("<!-- generated %s; toolchain: %s -->" % (datetime.date.today().isoformat(), toolchain))
w("")
w("What the Swift runtime is measured against, and how it did on the last run of the parity suites.")
w("")
w("- Upstream: <%s>" % upstream["repository"])
w("- Release: %s, commit `%s` (`%s`)" % (upstream["release"], upstream["commit"], upstream["commit"][:7]))
w("- Licence: %s (%s). The fixtures keep it; see `Tests/ParityFixtures/upstream/LICENSE-json-render`." % (upstream["licence"], upstream["copyright"]))
w("- Fixture layout and how each folder was made: `Tests/ParityFixtures/README.md`.")
w("")
w("## Upstream fixtures")
w("")
w("| Folder | Upstream source | Cases | Test functions | Result |")
w("|---|---|---:|---:|---|")
total_cases = total_tests = bad = 0
for folder, suites in UPSTREAM:
    cases = count_rows("upstream/" + folder) if folder not in ("prompt", "schema") else len(
        [f for f in os.listdir(os.path.join(fixtures, "upstream", folder)) if f.endswith((".txt", ".json")) and f != "catalogs.json"])
    tests, result = verdict(suites)
    total_cases += cases
    total_tests += tests
    bad += result != "pass"
    w("| `upstream/%s/` | %s | %d | %d | %s |" % (folder, sources(folder), cases, tests, result))
w("")
w("## Our own fixtures")
w("")
w("Sibling folders of `upstream/`. They are not upstream material.")
w("")
w("| Folder | What it holds | Cases | Test functions | Result |")
w("|---|---|---:|---:|---|")
for folder, what, suites in OWN:
    if folder == "compose":
        cases = len([d for d in os.listdir(os.path.join(fixtures, "compose")) if os.path.isdir(os.path.join(fixtures, "compose", d))])
    elif folder == "streams":
        cases = len(json.load(open(os.path.join(fixtures, "streams", "index.json"), encoding="utf-8")))
    else:
        cases = count_rows(folder)
    tests, result = verdict(suites)
    bad += result != "pass"
    w("| `%s/` | %s | %d | %d | %s |" % (folder, what, cases, tests, result))
w("")
w("## Totals")
w("")
w("- Upstream fixture cases: %d in %d folders." % (total_cases, len(UPSTREAM)))
w("- Test functions that read the fixture folders: %d passed, %d failed, %d skipped." % (
    sum(r["passed"] for r in results.values()), sum(r["failed"] for r in results.values()),
    sum(r["skipped"] for r in results.values())))
w("- Folders not passing: %d." % bad)
w("")
w("A parameterised Swift Testing test is one test function that runs every case, so the case counts above come from the fixture folders, and `FixtureInventoryTests` guards each count against a wrong path that would run zero cases.")
w("")
w("## Not upstream")
w("")
w("The runtime does more than upstream in a few places. Each one is documented and tested on its own; none changes the meaning of a spec that upstream accepts.")
w("")
w("- Built-in actions `toggleState` and `incrementState`. `PromptOptions(includeExtensions: false)` removes them from the prompt, so a spec can also run on the web.")
w("- The `+` props: optional extras on top of upstream props (for example `Card.variant`, `Stack.wrap`, `Table.sortable`, `Button.size`). The prompt line equals upstream's once the extras are removed (`StandardCatalogPromptTests`).")
w("- Slots beyond upstream's: the named slots of `Card`, `Dialog`, `Drawer`, `Image`, `Table` and the charts.")
w("- Deviations where the Swift behaviour is safer: a `visible` shape the runtime cannot evaluate is hidden (upstream sometimes shows it); `pushState` with `$id` gives a UUID string; every action honours `confirm`; a pattern check that could take exponential time is refused with a neutral message.")
w("- Whole modules with no upstream counterpart: the 15 charts, the streaming layer on a display link, the composer on the OpenAI Decisions API, and the style, theme and slot layers.")
w("")
w("---")
w("")
w("Generated by `Scripts/parity-report.sh`; do not edit.")
print("\n".join(out))
