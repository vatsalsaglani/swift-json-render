// Merges data/catalog.generated.json (from tools/dump-catalog.sh) into data/components.json.
// The catalogs know better than the hand-written draft: this replaces `description`, `events`,
// `slots` and `props` of every standard and chart entry, and keeps the hand-written parts the
// site needs (`group`, `swiftui`, `variants`, `examples`, and per prop `default`, `bindable`
// and a non-empty `note`). Rafu entries are untouched and marked "source": "planned".
//
// Run: node site/tools/merge-catalog.mjs   (then: node site/tools/sync-data.mjs)
// It fails when a catalog and the registry disagree on the component names. It warns when an
// example uses a prop the catalog does not have: fix that example by hand in the same change,
// because tests/check.mjs renders every example.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'data');
const registryPath = path.join(dir, 'components.json');
const doc = JSON.parse(fs.readFileSync(registryPath, 'utf8'));
const generated = JSON.parse(fs.readFileSync(path.join(dir, 'catalog.generated.json'), 'utf8'));

const COUNTS = { standard: 36, charts: 15 };
const problems = [];
const warnings = [];

for (const catalog of ['standard', 'charts']) {
  const fresh = new Map(generated[catalog].map((e) => [e.name, e]));
  const entries = doc.components.filter((c) => c.catalog === catalog);
  if (fresh.size !== COUNTS[catalog]) problems.push(`${catalog}: the catalog has ${fresh.size} entries, expected ${COUNTS[catalog]}`);
  if (entries.length !== COUNTS[catalog]) problems.push(`${catalog}: the registry has ${entries.length} entries, expected ${COUNTS[catalog]}`);
  for (const entry of entries) {
    const gen = fresh.get(entry.name);
    if (!gen) { problems.push(`${catalog}: ${entry.name} is in the registry but not in the catalog`); continue; }
    fresh.delete(entry.name);

    if (gen.description) entry.description = gen.description;
    entry.events = [...gen.events];
    // "default" means "accepts children"; the site lists named slots only.
    entry.slots = gen.slots.filter((s) => s !== 'default');

    const old = new Map(entry.props.map((p) => [p.name, p]));
    entry.props = gen.props.map((p) => {
      const before = old.get(p.name) || {};
      const out = {
        name: p.name,
        type: p.type,
        required: p.required,
        default: before.default === undefined ? null : before.default,
        note: before.note || p.note || '',
      };
      if (before.bindable) out.bindable = true;
      return out;
    });
    entry.source = 'Catalog';

    const known = new Set(gen.props.map((p) => p.name));
    for (const ex of entry.examples) {
      for (const [id, el] of Object.entries(ex.spec.elements)) {
        if (el.type !== entry.name) continue;
        for (const prop of Object.keys(el.props || {})) {
          if (!known.has(prop)) warnings.push(`${entry.name} example "${ex.title}", element ${id}: prop "${prop}" is not in the catalog`);
        }
      }
    }
    for (const vr of entry.variants) {
      for (const prop of Object.keys(vr.props || {})) {
        if (!known.has(prop)) warnings.push(`${entry.name} variant "${vr.label}": prop "${prop}" is not in the catalog`);
      }
    }
  }
  for (const name of fresh.keys()) problems.push(`${catalog}: ${name} is in the catalog but not in the registry`);
}

for (const entry of doc.components) if (entry.catalog === 'rafu') entry.source = 'planned';

doc.meta.generatedFrom = generated.generatedFrom;
doc.meta.status = 'standard catalog and charts generated from the Swift package; Rafu additions planned';
doc['$comment'] = 'Registry for the showcase site. The standard and chart entries are merged from the Swift catalogs by tools/merge-catalog.mjs (description, props, events, slots); examples, variants, swiftui and the Rafu entries are hand-written. components.js is generated by tools/sync-data.mjs.';

// The footers name the commit the data came from.
const short = generated.generatedFrom.slice(0, 7);
for (const name of fs.readdirSync(path.join(dir, '..')).filter((f) => f.endsWith('.html'))) {
  const file = path.join(dir, '..', name);
  const html = fs.readFileSync(file, 'utf8');
  const next = html.replace(/(<span data-gen-sha>)[^<]*(<\/span>)/g, '$1' + short + '$2');
  if (next !== html) fs.writeFileSync(file, next);
}

if (problems.length) { problems.forEach((p) => console.error('ERROR ' + p)); process.exit(1); }
warnings.forEach((w) => console.warn('WARN  ' + w));
fs.writeFileSync(registryPath, JSON.stringify(doc, null, 2) + '\n');
console.log(`merged ${COUNTS.standard} standard and ${COUNTS.charts} chart entries from ${generated.generatedFrom.slice(0, 7)}; ${warnings.length} warnings`);
